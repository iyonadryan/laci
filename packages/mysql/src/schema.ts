/** One schema change, applied once and recorded in the migrations table. */
export interface Migration {
  version: number;
  name: string;
  /**
   * DDL statements. MySQL commits DDL implicitly, so each statement is idempotent: a migration
   * that failed halfway can simply run again.
   */
  statements: string[];
}

/** Table prefixes are interpolated into SQL, so they are restricted to safe identifiers. */
export const TABLE_PREFIX_PATTERN = /^[a-z_][a-z0-9_]{0,30}$/;

/** Throws when `prefix` could not be used safely in table names. */
export function assertTablePrefix(prefix: string): void {
  if (!TABLE_PREFIX_PATTERN.test(prefix)) {
    throw new TypeError(
      `Laci: invalid table prefix "${prefix}"; use lowercase letters, digits, and "_" (max 31).`,
    );
  }
}

const TABLE_OPTIONS = 'ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin';

/** The table that records applied migrations. */
export function migrationsTable(p: string): string {
  return `CREATE TABLE IF NOT EXISTS ${p}migrations (
  version     INT          NOT NULL PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  applied_at  DATETIME(3)  NOT NULL DEFAULT (UTC_TIMESTAMP(3))
) ${TABLE_OPTIONS}`;
}

/**
 * All migrations, oldest first. `p` is the table prefix.
 *
 * - `locale` and `channel` are `''` when not set (the API shows `null`), so that the UNIQUE key
 *   treats "no locale" as one value: MySQL never considers two NULLs equal.
 * - `schema` and `value` are `LONGTEXT` checked with `JSON_VALID`, not `JSON`: MySQL's `JSON`
 *   type re-sorts object keys, and the editor shows fields in the order they were written.
 * - `key` and `schema` are reserved words in MySQL, hence the backticks.
 */
export function migrations(p: string): Migration[] {
  return [
    {
      version: 1,
      name: 'initial schema',
      statements: [
        `CREATE TABLE IF NOT EXISTS ${p}entries (
  id           BINARY(16)   NOT NULL PRIMARY KEY,
  \`key\`        VARCHAR(191) NOT NULL,
  kind         VARCHAR(20)  NOT NULL,
  environment  VARCHAR(50)  NOT NULL,
  locale       VARCHAR(35)  NOT NULL DEFAULT '',
  channel      VARCHAR(20)  NOT NULL DEFAULT '',
  description  TEXT,
  \`schema\`     LONGTEXT     NOT NULL,
  value        LONGTEXT     NOT NULL,
  status       VARCHAR(20)  NOT NULL,
  version      INT          NOT NULL,
  created_by   VARCHAR(255),
  updated_by   VARCHAR(255),
  created_at   DATETIME(3)  NOT NULL DEFAULT (UTC_TIMESTAMP(3)),
  updated_at   DATETIME(3)  NOT NULL DEFAULT (UTC_TIMESTAMP(3)),
  UNIQUE KEY uq_${p}entries_address (\`key\`, environment, locale, channel),
  KEY idx_${p}entries_kind (kind, environment),
  CONSTRAINT ck_${p}entries_kind CHECK (kind IN ('CONFIG', 'EMAIL_TEMPLATE', 'MESSAGE_TEMPLATE')),
  CONSTRAINT ck_${p}entries_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'DISABLED')),
  CONSTRAINT ck_${p}entries_channel CHECK (channel IN ('', 'WHATSAPP', 'SMS', 'PUSH', 'IN_APP')),
  CONSTRAINT ck_${p}entries_schema CHECK (JSON_VALID(\`schema\`)),
  CONSTRAINT ck_${p}entries_value CHECK (JSON_VALID(value))
) ${TABLE_OPTIONS}`,
        `CREATE TABLE IF NOT EXISTS ${p}entry_histories (
  id          BINARY(16)  NOT NULL PRIMARY KEY,
  entry_id    BINARY(16)  NOT NULL,
  version     INT         NOT NULL,
  value       LONGTEXT    NOT NULL,
  \`schema\`    LONGTEXT    NOT NULL,
  status      VARCHAR(20) NOT NULL,
  changed_by  VARCHAR(255),
  changed_at  DATETIME(3) NOT NULL DEFAULT (UTC_TIMESTAMP(3)),
  note        TEXT,
  UNIQUE KEY uq_${p}entry_histories_version (entry_id, version),
  FOREIGN KEY (entry_id) REFERENCES ${p}entries (id),
  CONSTRAINT ck_${p}histories_value CHECK (JSON_VALID(value)),
  CONSTRAINT ck_${p}histories_schema CHECK (JSON_VALID(\`schema\`))
) ${TABLE_OPTIONS}`,
      ],
    },
  ];
}

/** The whole schema as one SQL script, for applying it without `migrate()`. */
export function schemaSql(p = 'laci_'): string {
  assertTablePrefix(p);
  const parts = [
    '-- Laci schema for MySQL 8. Generated by `pnpm --filter @lacijs/mysql schema`;',
    '-- do not edit by hand. Equivalent to `MySqlStore#migrate()` with the default prefix.',
    '',
    `${migrationsTable(p)};`,
  ];
  for (const migration of migrations(p)) {
    parts.push('', `-- ${migration.version}: ${migration.name}`);
    for (const statement of migration.statements) parts.push(`${statement};`);
    parts.push(
      `INSERT INTO ${p}migrations (version, name) VALUES (${migration.version}, '${migration.name}');`,
    );
  }
  return `${parts.join('\n')}\n`;
}
