/** One schema change, applied once and recorded in the migrations table. */
export interface Migration {
  version: number;
  name: string;
  statements: string[];
}

/** Table prefixes are interpolated into SQL, so they are restricted to safe identifiers. */
export const TABLE_PREFIX_PATTERN = /^[a-z_][a-z0-9_]{0,30}$/;

/** Throws when `prefix` could not be used safely in table names. */
export function assertTablePrefix(prefix: string): void {
  if (!TABLE_PREFIX_PATTERN.test(prefix)) {
    throw new TypeError(
      `Laci: invalid table prefix "${prefix}"; use lowercase letters, digits, and "_" (max 31).`,
    );
  }
}

/** The table that records applied migrations. */
export function migrationsTable(p: string): string {
  return `CREATE TABLE IF NOT EXISTS ${p}migrations (
  version     INT          PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  applied_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
)`;
}

/**
 * All migrations, oldest first. `p` is the table prefix.
 *
 * - `locale` and `channel` are `''` when not set (the API shows `null`), so that the UNIQUE
 *   constraint treats "no locale" as one value: PostgreSQL never considers two NULLs equal.
 * - `schema` and `value` are `JSON`, not `JSONB`: `JSON` keeps the text as written, so object
 *   keys keep their order (the editor shows fields in that order). Laci never queries inside
 *   values, so `JSONB`'s indexing would not help.
 */
export function migrations(p: string): Migration[] {
  return [
    {
      version: 1,
      name: 'initial schema',
      statements: [
        `CREATE TABLE ${p}entries (
  id           UUID         PRIMARY KEY,
  key          VARCHAR(191) NOT NULL,
  kind         VARCHAR(20)  NOT NULL,
  environment  VARCHAR(50)  NOT NULL,
  locale       VARCHAR(35)  NOT NULL DEFAULT '',
  channel      VARCHAR(20)  NOT NULL DEFAULT '',
  description  TEXT,
  schema       JSON         NOT NULL,
  value        JSON         NOT NULL,
  status       VARCHAR(20)  NOT NULL,
  version      INT          NOT NULL,
  created_by   VARCHAR(255),
  updated_by   VARCHAR(255),
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_${p}entries_address UNIQUE (key, environment, locale, channel),
  CONSTRAINT ck_${p}entries_kind CHECK (kind IN ('CONFIG', 'EMAIL_TEMPLATE', 'MESSAGE_TEMPLATE')),
  CONSTRAINT ck_${p}entries_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'DISABLED')),
  CONSTRAINT ck_${p}entries_channel CHECK (channel IN ('', 'WHATSAPP', 'SMS', 'PUSH', 'IN_APP'))
)`,
        `CREATE INDEX idx_${p}entries_kind ON ${p}entries (kind, environment)`,
        `CREATE TABLE ${p}entry_histories (
  id          UUID        PRIMARY KEY,
  entry_id    UUID        NOT NULL REFERENCES ${p}entries (id),
  version     INT         NOT NULL,
  value       JSON        NOT NULL,
  schema      JSON        NOT NULL,
  status      VARCHAR(20) NOT NULL,
  changed_by  VARCHAR(255),
  changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  note        TEXT,
  CONSTRAINT uq_${p}entry_histories_version UNIQUE (entry_id, version)
)`,
      ],
    },
  ];
}

/** The whole schema as one SQL script, for applying it without `migrate()`. */
export function schemaSql(p = 'laci_'): string {
  assertTablePrefix(p);
  const parts = [
    '-- Laci schema for PostgreSQL. Generated by `pnpm --filter @lacijs/postgres schema`;',
    '-- do not edit by hand. Equivalent to `PostgresStore#migrate()` with the default prefix.',
    '',
    `${migrationsTable(p)};`,
  ];
  for (const migration of migrations(p)) {
    parts.push('', `-- ${migration.version}: ${migration.name}`);
    for (const statement of migration.statements) parts.push(`${statement};`);
    parts.push(
      `INSERT INTO ${p}migrations (version, name) VALUES (${migration.version}, '${migration.name}');`,
    );
  }
  return `${parts.join('\n')}\n`;
}
